 WHERE NH.ID=I.NVDID AND I.PackageID=P.ID AND I.Status='Unpatched' 
 AND ((CAST(NH.SCOREV4 AS NUMERIC)>=7.0 AND CAST(NH.SCOREV4 AS NUMERIC)<9.0) OR
      (CAST(NH.SCOREV4 AS NUMERIC)<0.1 AND CAST(NH.SCOREV3 AS NUMERIC)>=7.0 AND CAST(NH.SCOREV3 AS NUMERIC)<9.0) OR     
